# What follows the type of a column, and whether the column can be null then.
CONSTRAINTS = [
    ("", True),
    ("NULL", True),
    ("NOT NULL", False),
    ("DEFAULT 0", True),  # a default says nothing about null
    ("NOT NULL DEFAULT 0", False),
    ("PRIMARY KEY", False),
]

suffixes = st.text(alphabet="abcdefghijklmnopqrstuvwxyz0123456789", max_size=5)


def distinct(prefix: str, low: int, high: int) -> st.SearchStrategy[list[str]]:
    """Names that cannot be equal, as the position of each one is in it: no draw is wasted."""
    return st.lists(suffixes, min_size=low, max_size=high).map(
        lambda found: [f"{prefix}{index}{suffix}" for index, suffix in enumerate(found)]
    )


comment_text = st.text(alphabet="abcXYZ 019.,;:-_()/é\t\n", max_size=40)
enum_values = distinct("v", 1, 14)


@dataclass(frozen=True)
class Column:
    """A column and what the importer must make of it."""

    name: str
    sql_type: str
    constraint: str
    comment: str | None
    in_table_key: bool  # listed in a PRIMARY KEY (...) of the table
    expected: tuple[str, str, bool, str]  # name, type, nullable, description


def with_note(comment: str, note: str) -> str:
    """The description of a column with a comment and the values of its enum."""
    if not comment:
        return note
    return f"{comment}{' ' if comment.endswith(('.', '!', '?')) else '. '}{note}"


def one_line(text: str) -> str:
    return " ".join(text.split())


def note_of(values: list[str]) -> str:
    shown = ", ".join(values[:10])
    return f"One of: {shown}" + (f", … ({len(values)} values)" if len(values) > 10 else "")


@st.composite
def columns(draw: st.DrawFn, flavour: Flavour, name: str) -> Column:
    """A column of the flavour, worked out together with what it has to give."""
    sql_type, field_type = draw(st.sampled_from(flavour.types))
    constraint, nullable = draw(st.sampled_from(CONSTRAINTS))
    if flavour.counters and draw(st.integers(0, 4)) == 0:  # a column that counts is never null
        (sql_type, constraint), field_type, nullable = (
            draw(st.sampled_from(flavour.counters)),
            "integer",
            False,
        )
    in_table_key = draw(st.booleans())
    comment = draw(st.none() | comment_text) if flavour.comments != "none" else None
    description = one_line(comment or "")
    expected = (name, field_type, nullable and not in_table_key, description)
    return Column(name, sql_type, constraint, comment, in_table_key, expected)


@st.composite
def enum_columns(draw: st.DrawFn, name: str) -> Column:
    """A MySQL column that is an enum, with the description its values give."""
    values = draw(enum_values)
    comment = draw(st.none() | comment_text)
    sql_type = "enum(" + ", ".join(f"'{value}'" for value in values) + ")"
    description = with_note(one_line(comment or ""), note_of(values))
    return Column(name, sql_type, "NOT NULL", comment, False, (name, "string", False, description))


@st.composite
def tables(draw: st.DrawFn) -> tuple[Flavour, list[Column]]:
    flavour = draw(st.sampled_from(FLAVOURS))
    column_names = draw(distinct("col_", 1, 8))
    result: list[Column] = []
    for name in column_names:
        if flavour is MYSQL and draw(st.integers(0, 5)) == 0:
            result.append(draw(enum_columns(name)))
        else:
            result.append(draw(columns(flavour, name)))
    return flavour, result


# ------------------------------------------------------------------- writing it as SQL


def column_sql(column: Column, flavour: Flavour, case: Any) -> str:
    """The definition of a column; ``case`` is applied to the words that are not names."""
    parts = [column.name, case(column.sql_type), case(column.constraint)]
    if column.comment is not None and flavour.comments == "inline":
        parts.append(case("COMMENT") + " '" + column.comment + "'")
    return " ".join(part for part in parts if part)


def create_table(
    name: str, flavour: Flavour, cols: list[Column], *, case: Any = str, gap: str = " "
) -> str:
    """``CREATE TABLE`` for the columns; the ones in a table key are listed in ``PRIMARY KEY``."""
    items = [column_sql(column, flavour, case) for column in cols]
    key = [column.name for column in cols if column.in_table_key]
    if key:
        items.append(f"{case('PRIMARY KEY')} ({', '.join(key)})")
    body = f",{gap}".join(items)
    return f"{case('CREATE TABLE')} {name} ({gap}{body}{gap})"


def comment_statements(name: str, flavour: Flavour, cols: list[Column]) -> list[str]:
    """``COMMENT ON COLUMN`` for the comments that a dialect does not write in the column."""
    if flavour.comments != "statement":
        return []
    return [
        f"COMMENT ON COLUMN {name}.{column.name} IS '{column.comment}'"
        for column in cols
        if column.comment is not None
    ]


def fields_of(sql: str, flavour: Flavour, **options: Any) -> list[tuple[str, str, bool, str]]:
    result = import_sql(sql, source="gen.sql", dialect=flavour.dialect, **options)
    return [(f.name, str(f.type), f.nullable, f.description) for f in result.schema.fields]


@settings(max_examples=400)
@given(table=tables())
def test_a_generated_table_gives_the_fields_it_was_built_from(
    table: tuple[Flavour, list[Column]],
) -> None:
    flavour, cols = table
    event(flavour.dialect or "standard")
    sql = ";\n".join([create_table("t", flavour, cols), *comment_statements("t", flavour, cols)])
    assert fields_of(sql, flavour) == [column.expected for column in cols]


@settings(max_examples=200)
@given(
    table=tables(),
    gap=st.sampled_from([" ", "\n    ", "\t", " /* a comment */ ", " -- a comment\n"]),
    upper=st.booleans(),
)
def test_keywords_in_any_case_and_any_space_between_the_words_change_nothing(
    table: tuple[Flavour, list[Column]], gap: str, upper: bool
) -> None:
    flavour, cols = table
    case = str.upper if upper else str.lower
    if flavour is MYSQL:
        cols = [c for c in cols if not c.sql_type.startswith("enum")]  # a value is not a keyword
    if not cols:
        return
    sql = create_table("t", flavour, cols, case=case, gap=gap)
    expected = [c.expected for c in cols]
    if flavour.comments == "statement":
        sql = ";\n".join([sql, *comment_statements("t", flavour, cols)])
    assert fields_of(sql, flavour) == expected


# --------------------------------------------------------------------------- a dump

NOISE = [
    "SET statement_timeout = 0",
    "SET client_encoding = 'UTF8'",
    "CREATE INDEX idx_noise ON elsewhere (a)",
    "CREATE VIEW v_noise AS SELECT 1",
    "GRANT SELECT ON elsewhere TO somebody",
    "CREATE SEQUENCE s_noise START WITH 1",
    "ALTER TABLE elsewhere OWNER TO somebody",
    "ALTER TABLE elsewhere ADD COLUMN x int",  # a table that this file does not create
    "COMMENT ON TABLE t IS 'about the table'",
    "COMMENT ON COLUMN elsewhere.x IS 'about another table'",
]


@st.composite
def dumps(draw: st.DrawFn) -> tuple[list[str], list[Column], list[Column]]:
    """The statements of a Postgres dump of a table, shuffled with noise; and what it gives."""
    cols = draw(
        distinct("col_", 1, 6).flatmap(
            lambda found: st.tuples(*[columns(POSTGRES, name) for name in found]).map(list)
        )
    )
    keyed = {c.name for c in cols if c.in_table_key}
    # The key of the table is added by ALTER TABLE, as pg_dump does, and not in the table.
    plain = [Column(c.name, c.sql_type, c.constraint, c.comment, False, c.expected) for c in cols]
    statements = [
        create_table("public.t", POSTGRES, plain),
        *comment_statements("public.t", POSTGRES, cols),
    ]
    if keyed:
        key = ", ".join(sorted(keyed))
        statements.append(f"ALTER TABLE ONLY public.t ADD CONSTRAINT t_pkey PRIMARY KEY ({key})")
    statements += draw(st.lists(st.sampled_from(NOISE), max_size=6))
    order = draw(st.permutations(statements))
    return list(order), cols, plain


@settings(max_examples=300)
@given(dump=dumps())
def test_the_order_of_a_dump_and_the_statements_left_out_change_nothing(
    dump: tuple[list[str], list[Column], list[Column]],
) -> None:
    statements, cols, _ = dump
    sql = ";\n".join(statements) + ";"
    assert fields_of(sql, POSTGRES, select="t") == [column.expected for column in cols]


# ----------------------------------------------------------------- choosing a table

WHOLE_NAMES = [schema + name for schema in ["", "one.", "two.", "three."] for name in "abc"]


@st.composite
def files(draw: st.DrawFn) -> tuple[str, dict[str, list[str]]]:
    """Several tables of a file in some order, and the names of the columns of each by full name."""
    full_names = sorted(draw(st.sets(st.sampled_from(WHOLE_NAMES), min_size=1, max_size=5)))
    by_full: dict[str, list[str]] = {}
    statements: list[str] = []
    for index, full in enumerate(full_names):
        found = [f"col_{index}{letter}" for letter in "xyz"[: draw(st.integers(1, 3))]]
        by_full[full] = found
        statements.append(f"CREATE TABLE {full} ({', '.join(c + ' int' for c in found)})")
    return ";\n".join(draw(st.permutations(statements))) + ";", by_full


def simple(full: str) -> str:
    return full.rpartition(".")[2]


@settings(max_examples=200)
@given(file=files())
def test_select_finds_every_table_by_its_whole_name_or_by_its_name_alone(
    file: tuple[str, dict[str, list[str]]],
) -> None:
    sql, by_full = file
    wanted = {*by_full, *(simple(full) for full in by_full), "nope"}
    for select in sorted(wanted):
        if select in by_full:  # a whole name is taken as it is, whatever else ends with it
            expected: list[str] | None = by_full[select]
        else:
            ends = [full for full in by_full if simple(full) == select]
            expected = by_full[ends[0]] if len(ends) == 1 else None
        found = outcome(partial(import_sql, sql, source="gen.sql", select=select))
        if expected is None:
            assert found[:2] == ("refused", UNSUPPORTED)
        else:
            assert found[0] == "imported"
            assert [f.name for f in found[1].fields] == expected


@settings(max_examples=100)
@given(file=files())
def test_a_file_of_several_tables_needs_select_and_one_table_needs_none(
    file: tuple[str, dict[str, list[str]]],
) -> None:
    sql, by_full = file
    found = outcome(lambda: import_sql(sql, source="gen.sql"))
    if len(by_full) == 1:
        assert found[0] == "imported"
        assert [f.name for f in found[1].fields] == next(iter(by_full.values()))
    else:
        assert found[:2] == ("refused", UNSUPPORTED)


# ------------------------------------------------------------- what has no equivalent

REFUSED_TYPES = [
    (POSTGRES, "int4range"),
    (POSTGRES, "geometry(Point, 4326)"),
    (POSTGRES, "oid"),
    (POSTGRES, "mystery_type"),
    (MYSQL, "geometry"),
    (SNOWFLAKE, "GEOGRAPHY"),
    (SNOWFLAKE, "VECTOR(FLOAT, 3)"),
]


@st.composite
def mixed_tables(draw: st.DrawFn) -> tuple[Flavour, list[tuple[Column, bool]]]:
    """A table where some columns have a type with no equivalent: (column, is that one)."""
    flavour = draw(st.sampled_from([POSTGRES, MYSQL, SNOWFLAKE]))
    refused = [sql_type for flavoured, sql_type in REFUSED_TYPES if flavoured is flavour]
    result: list[tuple[Column, bool]] = []
    for name in draw(distinct("col_", 1, 8)):
        if draw(st.booleans()):
            constraint, nullable = draw(st.sampled_from(CONSTRAINTS))
            column = Column(
                name,
                draw(st.sampled_from(refused)),
                constraint,
                None,
                False,
                (name, "json", nullable, ""),
            )
            result.append((column, True))
        else:
            result.append((draw(columns(flavour, name)), False))
    return flavour, result


@settings(max_examples=200)
@given(table=mixed_tables())
def test_strict_lists_every_column_with_no_equivalent_and_lenient_makes_them_json(
    table: tuple[Flavour, list[tuple[Column, bool]]],
) -> None:
    flavour, marked = table
    cols = [column for column, _ in marked]
    refused = [column.name for column, is_refused in marked if is_refused]
    sql = ";\n".join([create_table("t", flavour, cols), *comment_statements("t", flavour, cols)])
    strict = outcome(lambda: import_sql(sql, source="gen.sql", dialect=flavour.dialect))
    lenient = outcome(
        lambda: import_sql(sql, source="gen.sql", dialect=flavour.dialect, lenient=True)
    )
    event("refused" if refused else "nothing refused")
    if not refused:
        assert strict[0] == lenient[0] == "imported"
        assert strict[2] == lenient[2] == ()
        return
    assert strict[:2] == ("refused", UNSUPPORTED)
    assert all(f"t.{name}" in strict[2] for name in refused)
    assert lenient[0] == "imported"
    schema: Schema = lenient[1]
    assert [(f.name, str(f.type)) for f in schema.fields if f.name in refused] == [
        (name, "json") for name in refused
    ]
    assert [issue.code for issue in lenient[2]] == [IssueCode.DEGRADED_TO_JSON] * len(refused)
    assert [issue.pointer.split(" ")[0] for issue in lenient[2]] == [f"t.{n}" for n in refused]


