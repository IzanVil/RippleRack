valid_sql = tables().map(lambda table: create_table("t", table[0], table[1]) + ";")


@st.composite
def nearly_sql(draw: st.DrawFn) -> str:
    """A valid table with one place changed: a character gone, repeated, swapped or replaced."""
    sql = draw(valid_sql)
    at = draw(st.integers(0, len(sql) - 1))
    change = draw(st.sampled_from(["delete", "repeat", "replace", "cut"]))
    if change == "delete":
        return sql[:at] + sql[at + 1 :]
    if change == "repeat":
        return sql[:at] + sql[at] + sql[at:]
    if change == "cut":
        return sql[:at]
    return sql[:at] + draw(st.sampled_from("(),;'\"`-*/ x1")) + sql[at + 1 :]


@settings(max_examples=500)
@given(
    text=st.one_of(st.text(max_size=120), token_soup, nearly_sql()),
    dialect=dialects,
    lenient=st.booleans(),
)
def test_any_text_gives_a_schema_or_a_ripplerack_error(
    text: str, dialect: str | None, lenient: bool
) -> None:
    result = outcome(lambda: import_sql(text, source="fuzz.sql", dialect=dialect, lenient=lenient))
    event(result[0])
    if result[0] == "imported":
        schema: Schema = result[1]
        assert Schema.model_validate(yaml.safe_load(render_schema_yaml(schema))) == schema
    else:
        assert result[1] in {
            ErrorCode.INVALID_SQL,
            ErrorCode.UNSUPPORTED_SQL,
            ErrorCode.VALIDATION_FAILED,
        }
