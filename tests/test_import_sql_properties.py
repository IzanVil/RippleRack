@dataclass(frozen=True)
class Flavour:
    """A dialect, the types it can spell and how it says what a column is for."""

    dialect: str | None
    types: tuple[tuple[str, str], ...]  # how it is written, and what RippleRack makes of it
    comments: str  # "inline" (COMMENT '...'), "statement" (COMMENT ON COLUMN) or "none"
    counters: tuple[tuple[str, str], ...] = ()  # a type and a constraint of a column that counts


