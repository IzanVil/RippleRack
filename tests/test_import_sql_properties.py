"""Properties of the SQL importer, checked on thousands of generated tables and dumps.

The examples are derived from each test (see the settings profile in ``conftest.py``), so
they are the same on every run: a failure here is a real one, and Hypothesis shrinks it to
the smallest file that still fails.

* **a model**: a table is generated together with the fields it has to give, worked out when
  each column is built and not by reading the SQL again, and the importer must give exactly those,
  in five dialects;
* **a dump**: the statements of a dump can come in any order and be mixed with the ones the
  import leaves out, and the schema is the same;
* **how it is written**: keywords in any case, any space and comments between the words change
  nothing;
* **choosing a table**: ``select`` finds each table of a file by its whole name and, if no other
  has it, by its name alone;
* **what has no equivalent**: strict mode lists every such column and ``--lenient`` turns each
  into a ``json`` field with a warning;
* **anything at all**: any text, and any text that is nearly SQL, gives a schema or a
  ``RippleRackError``, never another exception.
"""

